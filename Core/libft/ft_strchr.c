#include "libft.h"

char	*ft_strchr(const char *s, int c)
{
	char	temp_c;

	temp_c = c;
	while (*s != temp_c)
	{
		if (*s == '\0')
			return (NULL);
		s++;
	}
	return ((char *)s);
}
